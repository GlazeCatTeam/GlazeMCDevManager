/** Return fresh protocol defaults; never share mutable arrays between works */
export function emptyWorkUpdate(): WorkRecord {
  return {
    ...Object.fromEntries(textFields.map((key) => [key, ""])),
    ...Object.fromEntries(numberFields.map((key) => [key, 0])),
    ...Object.fromEntries(booleanFields.map((key) => [key, false])),
    ...Object.fromEntries(arrayFields.map((key) => [key, []])),
    is_original: true,
    pre_review_video: "{}",
    multi_tags: "0",
    exchange_currency_type: "ordinary",
    decompose_currency_type: "ordinary",
    running_status: "normal",
    collection_id: "0",
    relate_item_id: "0",
    subject_id: null,
    openbeta_time: null,
    commercial_time: null,
    dyeing_relation: {},
    joint_activity_detail: {},
    dlc_info: { dlc_switch: false, dlc_type: "off", master: {}, slave_list: [] },
  };
}

/** Normalize documented empty-string sentinels without replacing populated platform metadata */
export function normalizeWorkUpdateDefaults(value: WorkRecord): void {
  for (const [key, fallback] of Object.entries({
    pre_review_video: "{}",
    multi_tags: "0",
    exchange_currency_type: "ordinary",
    decompose_currency_type: "ordinary",
    running_status: "normal",
    collection_id: "0",
  })) {
    if (value[key] === "" || value[key] == null) value[key] = fallback;
  }
  if (value.subject_id === "") value.subject_id = null;
  if (value.corp_proof_image === "" || value.corp_proof_image === null) delete value.corp_proof_image;
}
